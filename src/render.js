/* --------------------------------- data shaping --------------------------------- */

function buildPosts(events, startedAt) {
  const t0 = startedAt ? Date.parse(startedAt) : NaN;
  const posts = [];
  let current = null;
  for (const e of events) {
    if (e.type === 'prompt') {
      current = { prompt: e, items: [] };
      posts.push(current);
    } else if (current && (e.type === 'tool_call' || e.type === 'assistant_text')) {
      current.items.push(e);
    }
  }
  if (posts.length === 0 && events.length > 0) {
    posts.push({ prompt: { text: '(session without captured prompt)', timestamp: null }, items: events.filter(e => e.type === 'tool_call' || e.type === 'assistant_text') });
  }

  return posts.map((p, i) => {
    const comments = threadify(p.items);
    const calls = p.items.filter(e => e.type === 'tool_call');
    const filesTouched = new Set(calls.filter(c => c.file).map(c => c.file));
    return {
      n: i + 1,
      prompt: p.prompt,
      comments,
      ops: calls.length,
      nFiles: filesTouched.size,
      offset: offsetLabel(p.prompt.timestamp, t0),
      t0,
    };
  });
}

function threadify(items) {
  const comments = [];
  let current = null;
  for (const e of items) {
    if (e.type === 'assistant_text') {
      if (!e.text?.trim()) continue;
      current = { text: e.text, timestamp: e.timestamp, runs: [] };
      comments.push(current);
    } else if (e.type === 'tool_call') {
      if (!current) {
        current = { text: null, timestamp: e.timestamp, runs: [] };
        comments.push(current);
      }
      const last = current.runs[current.runs.length - 1];
      if (last && last.tool === e.tool && last.action === e.action) {
        last.count++;
        if (e.file) last.files.add(e.file);
        if (e.args?.command) last.cmds.push(e.args.command);
      } else {
        current.runs.push({
          tool: e.tool,
          action: e.action ?? 'other',
          count: 1,
          files: new Set(e.file ? [e.file] : []),
          cmds: e.args?.command ? [e.args.command] : [],
          arg: summarizeArgs(e.tool, e.args),
        });
      }
    }
  }
  return comments;
}

