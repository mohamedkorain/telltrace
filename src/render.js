function splitPrompt(text) {
  const t = String(text ?? '').trim();
  const nl = t.indexOf('\n');
  if (nl === -1) {
    if (t.length <= 140) return { title: t, body: '' };
    return { title: t.slice(0, 139) + '…', body: t };
  }
  const first = t.slice(0, nl).trim();
  const title = first.length <= 140 ? first : first.slice(0, 139) + '…';
  return { title, body: t.slice(nl + 1).trim() };
}

function communityName(sourcePath) {
  if (!sourcePath) return 'session';
  const parts = String(sourcePath).split('/').filter(Boolean);
  const dir = parts.length >= 2 ? parts[parts.length - 2] : 'session';
  const cleaned = dir.replace(/^-Users-[^-]+-?/, '').replace(/^-+|-+$/g, '');
  return (cleaned || 'session').slice(0, 40);
}

function offsetLabel(ts, t0) {
  const t = Date.parse(ts);
  if (!Number.isFinite(t) || !Number.isFinite(t0)) return '·';
  const s = Math.max(0, Math.round((t - t0) / 1000));
  if (s < 60) return `+${s}s`;
  const m = Math.floor(s / 60);
  if (m < 60) return `+${m}m ${s % 60}s`;
  return `+${Math.floor(m / 60)}h ${m % 60}m`;
}

function summarizeArgs(tool, args) {
  if (!args || typeof args !== 'object') return '';
  if (args.file_path) return args.file_path;
  if (args.path) return args.path;
  if (args.command) return args.command;
  if (args.pattern) return args.pattern;
  if (args.query) return args.query;
  if (args.prompt) return args.prompt;
  if (args.url) return args.url;
  const first = Object.entries(args)[0];
  return first ? `${first[0]}=${String(first[1])}` : '';
}

function compact(n) {
  if (n >= 1e6) return (n / 1e6).toFixed(1).replace(/\.0$/, '') + 'M';
  if (n >= 1e3) return (n / 1e3).toFixed(1).replace(/\.0$/, '') + 'k';
  return String(n);
}

function shortPath(p) {
  const parts = String(p).split('/').filter(Boolean);
  if (parts.length <= 2) return p;
  return parts.slice(-2).join('/');
}

function truncate(s, n) {
  s = String(s);
  return s.length > n ? s.slice(0, n - 1) + '…' : s;
}

function escapeHtml(s) {
  return String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

function basename(p) {
  if (!p) return '';
  return String(p).split('/').pop();
}

function formatDate(ts) {
  const d = new Date(ts);
  if (isNaN(d)) return String(ts);
  return d.toLocaleString(undefined, { month: 'short', day: 'numeric', year: 'numeric', hour: '2-digit', minute: '2-digit' });
}

function formatClock(t) {
  const d = new Date(t);
  if (isNaN(d)) return '';
  return d.toLocaleTimeString(undefined, { hour: '2-digit', minute: '2-digit' });
}

function formatDuration(start, end) {
  if (!start || !end) return '—';
  const ms = Date.parse(end) - Date.parse(start);
  if (!Number.isFinite(ms) || ms < 0) return '—';
  const s = Math.floor(ms / 1000);
  if (s < 60) return `${s}s`;
  const m = Math.floor(s / 60);
  if (m < 60) return `${m}m ${s % 60}s`;
  return `${Math.floor(m / 60)}h ${m % 60}m`;
}

