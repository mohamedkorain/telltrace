function js() {
  return `
const tip = document.getElementById('tip');
let tipEl = null;
document.addEventListener('mouseover', e => {
  const t = e.target.closest('[data-tip]');
  if (t && t !== tipEl) { tipEl = t; tip.textContent = t.getAttribute('data-tip'); tip.hidden = false; }
  else if (!t && tipEl) { tipEl = null; tip.hidden = true; }
});
document.addEventListener('mousemove', e => {
  if (tip.hidden) return;
  const pad = 14; let x = e.clientX + pad, y = e.clientY + pad;
  const r = tip.getBoundingClientRect();
  if (x + r.width > innerWidth - 8) x = e.clientX - r.width - pad;
  if (y + r.height > innerHeight - 8) y = e.clientY - r.height - pad;
  tip.style.left = x + 'px'; tip.style.top = y + 'px';
});
document.addEventListener('click', e => {
  const fold = e.target.closest('[data-fold]');
  if (fold) { fold.parentElement.classList.toggle('folded'); return; }
  const col = e.target.closest('[data-collapse]');
  if (col) { document.getElementById(col.getAttribute('data-collapse'))?.classList.toggle('folded'); return; }
  const ex = e.target.closest('[data-expand]');
  if (ex) {
    const p = ex.previousElementSibling;
    p.classList.toggle('clamp');
    ex.textContent = p.classList.contains('clamp') ? 'Read more' : 'Show less';
    return;
  }
  const sort = e.target.closest('[data-sort]');
  if (sort) {
    document.querySelectorAll('.sort').forEach(b => b.classList.remove('active'));
    sort.classList.add('active');
    const feed = document.getElementById('posts');
    const posts = [...feed.children];
    if (sort.getAttribute('data-sort') === 'top') posts.sort((a, b) => (+b.dataset.ops) - (+a.dataset.ops));
    else posts.sort((a, b) => +a.id.slice(1) - +b.id.slice(1));
    posts.forEach(p => feed.appendChild(p));
  }
});
`;
}

